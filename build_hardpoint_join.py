def norm_tokens(s):
    return tokens(s)


def resolve_by_rule(stem, mount_keys, mounts=None):
    """An edition or paint model -> its base hull, BY RULE.

    The base is the LONGEST mount-data key whose words all appear, in order,
    inside the model's name. Longest wins so that Carrack_Expedition_w_C8X
    resolves to "Carrack Expedition" and not to "Carrack".

    Returns (key, why) or (None, why-not). An ambiguous match - two keys of
    equal length - returns None, because a match that could be two ships is not
    a match.
    """
    want = norm_tokens(stem)
    hits = []
    for key in mount_keys:
        kt = norm_tokens(key)
        if not kt:
            continue
        i = 0
        for w in want:
            if i < len(kt) and w == kt[i]:
                i += 1
        if i == len(kt):
            hits.append(key)
    if not hits:
        return None, "no mount-data key's words appear in this model's name"
    longest = max(len(norm_tokens(k)) for k in hits)
    best = sorted(k for k in hits if len(norm_tokens(k)) == longest)
    if len(best) > 1:
        # AN AMBIGUITY ONLY MATTERS IF THE ANSWERS DIFFER.
        #
        # F7C-M_Super_Hornet_Heartseeker_Mk_I matches both "F7C-M Super Hornet
        # Mk I" and "F7C-M Hornet Heartseeker Mk I" - five words each, neither
        # more specific than the other, and no tie-break between them that is
        # not arbitrary. But both carry the SAME ten mounts on the same ports
        # with the same published dimensions, so picking either produces exactly
        # the same page.
        #
        # So the tie is broken by asking whether it is a tie about anything. If
        # the candidates disagree on their mounts it stays a refusal, because
        # then the choice decides what a visitor sees.
        sigs = {json.dumps(mount_signature(mounts.get(k) or {})) for k in best} \
            if mounts else {"?"}
        if len(sigs) == 1 and "?" not in sigs:
            return best[0], ("%d keys match equally well (%s) and they carry "
                             "identical mount data, so the choice changes nothing"
                             % (len(best), ", ".join(best)))
        return None, "ambiguous: %s all match equally well and their mount data " \
                     "differs" % ", ".join(best)
    return best[0], "words of %r appear in order inside %r" % (best[0], stem)


def extents(geo):
    return sorted(geo["max"][k] - geo["min"][k] for k in range(3))


def hull_matches(geo_a, geo_b, tol=0.02):
    """Are these two model files the same hull?

    THIS IS THE CHECK THE PROPORTION GUARD CANNOT DO, and finding that out is
    what this function exists for. `resolve_frame` compares SHAPE and is
    deliberately blind to size, because the model library mixes metres,
    centimetres and normalised units. So it accepts a Gladius hull offered
    Hammerhead dimensions at err 0.11, well inside its 0.35 threshold - measured,
    not supposed. A scale band cannot rescue it either: 19 of the 167 placed
    ships legitimately sit between 0.2 and 0.8 model units per metre, so there is
    no gap to put a threshold in.

    An EDITION, though, is the same mesh with a different skin. Its bounding box
    should be the base hull's box to within rounding. That is a comparison
    between two things we hold, rather than between a model and a number, and it
    is the only one here that can actually tell a Gladius from a Hammerhead.

    Returns (ok, detail).
    """
    a, b = extents(geo_a), extents(geo_b)
    if min(a) <= 0 or min(b) <= 0:
        return False, "degenerate box"
    worst = max(abs(a[i] - b[i]) / max(a[i], b[i]) for i in range(3))
    return worst <= tol, "worst axis differs by %.1f%% (%s vs %s)" % (
        worst * 100,
        [round(v, 2) for v in a], [round(v, 2) for v in b])


def mount_signature(rec):
    """What a mount set IS, for comparing two of them."""
    ms = rec.get("mounts") or []
    return len(ms), sorted((m.get("port") or "") for m in ms)


def main():
    verify_only = "--verify" in sys.argv
    if not GEO or not os.path.isdir(GEO):
        sys.exit("SET CC_GEO_DIR to the folder written by\n"
                 "  node testing/_src/decode_glb_points.js <dir> <models...>\n"
                 "Nothing was written. Without vertices nothing can be placed, and "
                 "an empty result must not be mistaken for 'these ships have no "
                 "hardpoints'.")

    mounts = read_json(MOUNTS, "the extracted mount data")
    fleet = read_json(FLEET, "the hardpoints already placed by place_fleet.py")

    def geo_for(stem):
        p = os.path.join(GEO, stem + ".json")
        if not os.path.exists(p):
            return None
        return read_json(p, "decoded geometry for " + stem)

    # ---- THE PORT IS CHECKED AGAINST THE ORIGINAL -----------------------
    #
    # 100i is already in hardpoints_fleet.json, placed by place_fleet.py in the
    # sandbox. Placing it again here and comparing is what makes this port
    # trustworthy: a port that had drifted would disagree with the file it is
    # meant to match, and would say so here rather than on 29 ships' pages.
    control = geo_for("100i")
    verdict = None
    if control and "100i" in fleet:
        theirs = fleet["100i"]["hardpoints"]
        rec = mounts.get("100i")
        hps, frame, _ = place_ship(control, (rec or {}).get("mounts") or [],
                                   (rec or {}).get("dimension") or {})
        if hps is None:
            verdict = {"ok": False, "why": "the control ship would not place: %s" % frame}
        else:
            by_port = {h["port"]: h for h in hps}
            deltas = []
            for h in theirs:
                mine = by_port.get(h["port"])
                if not mine:
                    continue
                d = math.sqrt(sum((mine["unit"][k] - h["unit"][k]) ** 2 for k in range(3)))
                deltas.append(d)
            worst = max(deltas) if deltas else None
            # 0.10 in unit space is 5% of the hull's longest dimension. The
            # sandbox placed against EVERY vertex and this places against a
            # uniform sample, so the nearest vertex differs slightly and exact
            # equality is not the right test. A frame or nose error would move a
            # marker to the other end of the ship, which is far past this.
            verdict = {"ok": worst is not None and worst <= 0.10,
                       "compared": len(deltas),
                       "worst_unit_delta": round(worst, 4) if worst is not None else None,
                       "frame_matches": frame == fleet["100i"].get("frame")}
        say("port check against place_fleet.py's own output for the 100i:")
        say("  %s" % json.dumps(verdict))
        if not verdict.get("ok"):
            sys.exit("THE PORT DOES NOT REPRODUCE THE ORIGINAL. Nothing was written.\n"
                     "Placing 29 ships with a placement routine that disagrees with "
                     "the one that placed the other 167 would put two different "
                     "answers on one page.")
    else:
        say("port check SKIPPED - no control geometry. Decode 100i.glb to enable it.")
        verdict = {"ok": None, "why": "control geometry not present"}

    if verify_only:
        return 0

    # ---- what is missing ------------------------------------------------
    have_model = sorted(os.path.basename(p)[:-4]
                        for p in [os.path.join(MODELS, f) for f in os.listdir(MODELS)]
                        if p.lower().endswith(".glb"))
    placed_models = {v.get("model", "")[:-4] for v in fleet.values()}
    missing = [m for m in have_model if m not in placed_models]

    out, report = {}, {"placed": [], "refused": [], "skipped": [], "rule": [],
                       "mapped": [], "unchecked_hull": []}

    for stem in missing:
        key, why, how = None, "", ""
        if stem in E1:
            key, why, how = E1[stem], "listed in E1", "mapping"
        else:
            key, why = resolve_by_rule(stem, mounts.keys(), mounts)
            how = "rule"
        if not key:
            report["skipped"].append([stem, why])
            continue
        if key not in mounts:
            report["refused"].append([stem, key, "resolved to a key that does not exist"])
            continue

        rec = mounts[key]

        # THE MOUNT CHECK, where both sides exist.
        own = mounts.get(stem.replace("_", " "))
        if own:
            a, b = mount_signature(own), mount_signature(rec)
            if a != b:
                report["refused"].append([stem, key,
                    "mount data disagrees: %d mounts vs %d" % (a[0], b[0])])
                continue

        geo = geo_for(stem)
        if geo is None:
            report["skipped"].append([stem, "no decoded geometry"])
            continue

        # THE HULL CHECK - the only one that can tell a Gladius from a
        # Hammerhead. Runs where the base hull has a model of its own.
        hull_check = "not performed - the base hull has no model on disk"
        if how == "rule":
            base_model = (fleet.get(key) or {}).get("model") or ""
            base_geo = geo_for(base_model[:-4]) if base_model else None
            if base_geo is not None:
                ok, detail = hull_matches(geo, base_geo)
                if not ok:
                    report["refused"].append([stem, key,
                        "the model is not the same hull as %r: %s" % (key, detail)])
                    continue
                hull_check = "same hull as %r: %s" % (key, detail)
            else:
                report["unchecked_hull"].append([stem, key])

        hps, frame, crowded = place_ship(geo, rec.get("mounts") or [],
                                         rec.get("dimension") or {})
        if hps is None:
            # THE SHAPE CHECK REFUSING IS THE POINT, not a failure of it.
            report["refused"].append([stem, key, frame])
            continue

        out[stem] = {
            "maker": rec.get("maker"),
            "bare": stem,
            "model": stem + ".glb",
            "resolved_from": key,
            "resolved_by": how,
            "why": why,
            "hull_check": hull_check if how == "rule" else
                          "not applicable - this model IS that ship, under a "
                          "shorter file name",
            "dimension": rec.get("dimension"),
            "pilot_dps": rec.get("pilot_dps"),
            "pilot_alpha": rec.get("pilot_alpha"),
            "weapons": rec.get("weapons"),
            "frame": frame,
            "hardpoints": hps,
        }
        report[("mapped" if how == "mapping" else "rule")].append([stem, key, len(hps)])
        report["placed"].append([stem, len(hps), frame["shape_err"], crowded])

    if not os.path.isdir(OUTDIR):
        os.makedirs(OUTDIR)
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, separators=(",", ":"), ensure_ascii=False, sort_keys=True)
        fh.write("\n")
    with io.open(REPORT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(report, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    with io.open(MANIFEST, "w", encoding="utf-8", newline="\n") as fh:
        json.dump({
            "dataset": "holo-hardpoints-join",
            "produced_by": "build_hardpoint_join.py",
            "what_this_is": "Ships whose mount data already existed under a name "
                            "that did not join to the model file. Placed with a "
                            "pure-Python port of place_fleet.py's rules, checked "
                            "against that script's own output for a control ship.",
            "why_a_separate_file": "hardpoints_fleet.json has one writer, "
                                   "place_fleet.py. A second writer on one artifact "
                                   "is a defect this project has paid for three "
                                   "times.",
            "port_check": verdict,
            "counts": {"placed": len(out), "refused": len(report["refused"]),
                       "skipped": len(report["skipped"])},
        }, fh, indent=1, ensure_ascii=False)
        fh.write("\n")

    say("")
    say("wrote %s" % os.path.relpath(OUT, HERE))
    say("  recovered %d ship(s): %d by mapping, %d by rule"
        % (len(out), len(report["mapped"]), len(report["rule"])))
    total = sum(len(v["hardpoints"]) for v in out.values())
    say("  %d hardpoints placed" % total)
    for stem, key, n in sorted(report["mapped"]) + sorted(report["rule"]):
        say("    %-40s <- %-28s %3d mounts" % (stem, key, n))
    if report["refused"]:
        say("  REFUSED (%d) - reported rather than rendered:" % len(report["refused"]))
        for row in report["refused"]:
            say("    %-40s %s" % (row[0], row[2]))
    if report["unchecked_hull"]:
        say("  HULL CHECK NOT PERFORMED for %d pair(s) - the base hull has no "
            "model on disk to compare against. Reported, not counted as passed:"
            % len(report["unchecked_hull"]))
        for stem, key in report["unchecked_hull"]:
            say("    %-40s <- %s" % (stem, key))
    if report["skipped"]:
        say("  no resolution (%d), left as bare hulls:" % len(report["skipped"]))
        for row in report["skipped"][:40]:
            say("    %-40s %s" % (row[0], row[1]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
