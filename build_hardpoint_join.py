def tokens(s):
    return re.sub(r"[^a-z0-9]+", " ", str(s).lower()).split()


def read_location(where, port):
    t = tokens(where) + tokens(port)
    loc = {"side": None, "vert": None, "lon": None, "part": None, "index": None}
    if "left" in t or "port" in t:
        loc["side"] = "left"
    if "right" in t or "starboard" in t:
        loc["side"] = "right"
    if any(w in t for w in ("top", "upper", "dorsal")):
        loc["vert"] = "top"
    if any(w in t for w in ("bottom", "lower", "belly", "ventral", "under")):
        loc["vert"] = "bottom"
    if any(w in t for w in ("nose", "front", "fwd", "forward")):
        loc["lon"] = "front"
    if any(w in t for w in ("rear", "aft", "back", "tail")):
        loc["lon"] = "rear"
    if "mid" in t or "middle" in t:
        loc["lon"] = "mid"
    for part in ("wing", "pylon", "nose", "body", "hull", "turret",
                 "missilerack", "tractor", "chin", "roof", "canopy"):
        if part in t:
            loc["part"] = part
            break
    if loc["part"] is None:
        if "missile" in t and "rack" in t:
            loc["part"] = "missilerack"
        elif "countermeasure" in t or "cm" in t:
            loc["part"] = "countermeasure"
        elif "gun" in t or "weapon" in t or "laser" in t:
            loc["part"] = "gun"
    for w in t:
        if w.isdigit():
            loc["index"] = int(w)
            break
    return loc


TARGET = {
    "nose": (0.18, 0.50, 0.07), "chin": (0.16, 0.16, 0.16),
    "canopy": (0.14, 0.85, 0.26), "roof": (0.14, 0.92, 0.42),
    "wing": (0.88, 0.46, 0.52), "pylon": (0.72, 0.30, 0.56),
    "body": (0.34, 0.46, 0.44), "hull": (0.34, 0.46, 0.44),
    "turret": (0.16, 0.88, 0.46), "missilerack": (0.56, 0.62, 0.46),
    "countermeasure": (0.62, 0.44, 0.80), "tractor": (0.12, 0.20, 0.52),
    "gun": (0.62, 0.50, 0.36), None: (0.50, 0.50, 0.44),
}
LON_SHIFT = {"front": -0.18, "rear": 0.18, "mid": 0.0, None: 0.0}


def clip(v, lo, hi):
    return lo if v < lo else (hi if v > hi else v)


def target_uvw(loc, spread=0.0):
    u, v, w = TARGET[loc["part"] if loc["part"] in TARGET else None]
    u = -u if loc["side"] == "left" else (u if loc["side"] == "right" else 0.0)
    if loc["vert"] == "top":
        v = max(v, 0.86)
    elif loc["vert"] == "bottom":
        v = min(v, 0.14)
    w += LON_SHIFT[loc["lon"]] + spread
    if loc["index"]:
        w += (loc["index"] - 1) * 0.13 - 0.13
    return u, clip(v, 0.02, 0.98), clip(w, 0.02, 0.98)


def resolve_frame(mn, mx, dim):
    """Which bbox axis is length, width, height - decided on SHAPE, not size.

    Ported unchanged. The model library is not consistently scaled (metres,
    centimetres and normalised all appear), so proportions decide the axes and
    the scale is measured afterwards. A ship whose proportions do not match its
    own spec sheet is refused - which is exactly the guard that makes a wrong
    name mapping fail here instead of on a page.
    """
    ext = [mx[i] - mn[i] for i in range(3)]
    want = {"length": dim.get("length"), "width": dim.get("width"),
            "height": dim.get("height")}
    if not all(want.values()):
        return None, "no published dimensions", None
    if min(ext) <= 0:
        return None, "degenerate hull %r" % (ext,), None

    wn = [want["length"], want["width"], want["height"]]
    wmax = max(wn)
    wr = [x / float(wmax) for x in wn]

    best, best_err = None, 1e9
    emax = max(ext)
    for lat in range(3):
        for up in range(3):
            for lon in range(3):
                if len({lat, up, lon}) != 3:
                    continue
                er = [ext[lon] / emax, ext[lat] / emax, ext[up] / emax]
                err = sum(abs(er[i] - wr[i]) for i in range(3))
                if err < best_err:
                    best_err, best = err, (lat, up, lon)

    if best_err > 0.35:
        return None, ("proportions do not match published dims (err %.2f, ext %s, "
                      "want %s)" % (best_err, [round(e, 2) for e in ext], wn)), None

    scale = ext[best[2]] / float(want["length"])
    return best, best_err, scale


def nose_sign(pts, ix_len, ix_lat, ix_up):
    """Which end of the length axis is the nose. The tail is wide; the nose is
    narrow. Measured, never assumed."""
    n = len(pts) // 3
    zs = [pts[i * 3 + ix_len] for i in range(n)]
    lo, hi = min(zs), max(zs)
    span = hi - lo
    if span <= 0:
        return -1
    a_lat, a_up, b_lat, b_up = [], [], [], []
    for i in range(n):
        z = zs[i]
        if z <= lo + span * 0.15:
            a_lat.append(pts[i * 3 + ix_lat])
            a_up.append(pts[i * 3 + ix_up])
        elif z >= hi - span * 0.15:
            b_lat.append(pts[i * 3 + ix_lat])
            b_up.append(pts[i * 3 + ix_up])
    if len(a_lat) < 20 or len(b_lat) < 20:
        return -1
    spread_a = (max(a_lat) - min(a_lat)) + (max(a_up) - min(a_up))
    spread_b = (max(b_lat) - min(b_lat)) + (max(b_up) - min(b_up))
    return -1 if spread_a < spread_b else +1


def dist2(pts, i, x, y, z):
    a = pts[i * 3] - x
    b = pts[i * 3 + 1] - y
    c = pts[i * 3 + 2] - z
    return a * a + b * b + c * c


def place(pts, mn, mx, axes, nose, loc, spread=0.0, avoid=(), minsep=0.06):
    lat, up, lon = axes
    n = len(pts) // 3
    mid = (mn[lat] + mx[lat]) / 2.0
    half = max(mx[lat] - mid, mid - mn[lat]) or 1e-6
    ymin, yr = mn[up], (mx[up] - mn[up]) or 1e-6
    zmin, zr = mn[lon], (mx[lon] - mn[lon]) or 1e-6
    size = math.sqrt(sum((mx[k] - mn[k]) ** 2 for k in range(3)))

    # the hull's own centreline - nine models are not centred on 0
    if loc["side"] == "left":
        side_ok = [i for i in range(n) if pts[i * 3 + lat] < mid - half * 0.02]
    elif loc["side"] == "right":
        side_ok = [i for i in range(n) if pts[i * 3 + lat] > mid + half * 0.02]
    else:
        side_ok = None
    if side_ok is not None and len(side_ok) < 30:
        side_ok = None

    idxs = side_ok if side_ok is not None else range(n)

    p = None
    for attempt in range(9):
        u, v, w = target_uvw(loc, spread + attempt * 0.055 * (1 if attempt % 2 else -1))
        wz = w if nose < 0 else (1.0 - w)
        tx = mid + u * half
        ty = ymin + v * yr
        tz = zmin + wz * zr
        t = [0.0, 0.0, 0.0]
        t[lat], t[up], t[lon] = tx, ty, tz
        bi, bd = -1, None
        for i in idxs:
            d = dist2(pts, i, t[0], t[1], t[2])
            if bd is None or d < bd:
                bd, bi = d, i
        p = [pts[bi * 3], pts[bi * 3 + 1], pts[bi * 3 + 2]]
        if not avoid:
            return p, True
        gap = min(math.sqrt(sum((p[k] - a[k]) ** 2 for k in range(3))) for a in avoid)
        if gap > size * minsep:
            return p, True
    return p, False


def size_of(mn, mx):
    return math.sqrt(sum((mx[k] - mn[k]) ** 2 for k in range(3)))


def push_out(p, mn, mx, frac=0.012):
    c = [(mn[k] + mx[k]) / 2.0 for k in range(3)]
    d = [p[k] - c[k] for k in range(3)]
    nrm = math.sqrt(sum(v * v for v in d))
    if nrm < 1e-9:
        return list(p)
    size = size_of(mn, mx)
    return [p[k] + d[k] / nrm * size * frac for k in range(3)]


def to_unit(p, mn, mx):
    span = max(mx[k] - mn[k] for k in range(3)) or 1.0
    centre = [(mn[k] + mx[k]) / 2.0 for k in range(3)]
    return [round((p[k] - centre[k]) / (span / 2.0), 5) for k in range(3)]


def place_ship(geo, mounts, dim):
    """Every mount on one hull. Returns (hardpoints, frame, crowded) or an error."""
    pts, mn, mx = geo["pts"], geo["min"], geo["max"]
    axes, err, scale = resolve_frame(mn, mx, dim or {})
    if axes is None:
        return None, err, None
    nose = nose_sign(pts, axes[2], axes[0], axes[1])

    bykey = {}
    for mt in mounts:
        loc = read_location(mt["where"], mt["port"])
        bykey.setdefault((loc["side"], loc["vert"], loc["lon"], loc["part"]), []).append((mt, loc))

    hps, placed, crowded = [], [], 0
    for key in sorted(bykey, key=str):
        lst = bykey[key]
        cnt = len(lst)
        for i, (mt, loc) in enumerate(lst):
            sp = 0.0 if cnt == 1 else (i / (cnt - 1.0) - 0.5) * 0.34
            p, ok = place(pts, mn, mx, axes, nose, loc, sp, avoid=placed)
            placed.append(p)
            if not ok:
                crowded += 1
            pcm = push_out(p, mn, mx)
            item = mt.get("item") or {}
            hps.append({
                "where": mt["where"], "port": mt["port"],
                "kind": KIND.get(mt["type"], "other"),
                "pilot": None, "turretOf": None,
                "pos_model": [round(float(c), 3) for c in pcm],
                "unit": to_unit(pcm, mn, mx),
                "read": [k for k in ("side", "vert", "lon", "part") if loc[k]],
                "items": ([{"name": item.get("name"), "type": item.get("type"),
                            "size": item.get("size") or mt.get("size"),
                            "mfr": item.get("mfr"), "port": mt["port"]}]
                          if item.get("name") else []),
            })

    # left/right pairs are mirrored and re-snapped, then separation is
    # re-checked - both carried over from place_fleet.py, where mirroring on its
    # own took overlaps from 15 ships to 28.
    lat_i = axes[0]
    midx = (mn[lat_i] + mx[lat_i]) / 2.0
    groups = {}
    for h in hps:
        w = h["where"].lower()
        if " left" in w or " right" in w:
            k = w.replace(" left", " *").replace(" right", " *")
            groups.setdefault(k, {})[("left" if " left" in w else "right")] = h
    n = len(pts) // 3
    for k in groups:
        pair = groups[k]
        if len(pair) != 2:
            continue
        a, b = pair["left"], pair["right"]
        keep, other = ((a, b) if abs(a["pos_model"][lat_i] - midx)
                       >= abs(b["pos_model"][lat_i] - midx) else (b, a))
        tgt = list(keep["pos_model"])
        tgt[lat_i] = 2 * midx - tgt[lat_i]
        want_left = (other is a)
        if want_left:
            idxs = [i for i in range(n) if pts[i * 3 + lat_i] < midx]
        else:
            idxs = [i for i in range(n) if pts[i * 3 + lat_i] > midx]
        if len(idxs) < 10:
            continue
        bi, bd = -1, None
        for i in idxs:
            d = dist2(pts, i, tgt[0], tgt[1], tgt[2])
            if bd is None or d < bd:
                bd, bi = d, i
        snapped = [pts[bi * 3], pts[bi * 3 + 1], pts[bi * 3 + 2]]
        newp = push_out(snapped, mn, mx)
        other["pos_model"] = [round(float(c), 3) for c in newp]
        other["unit"] = to_unit(newp, mn, mx)

    minsep = size_of(mn, mx) * 0.02
    for i, h in enumerate(hps):
        q = h["pos_model"]
        others = [o["pos_model"] for j, o in enumerate(hps) if j != i]
        if not others:
            break
        if min(math.sqrt(sum((o[k] - q[k]) ** 2 for k in range(3))) for o in others) >= minsep:
            continue
        order = sorted(range(n), key=lambda i2: dist2(pts, i2, q[0], q[1], q[2]))[:4000]
        moved = False
        for idx in order:
            c = [pts[idx * 3], pts[idx * 3 + 1], pts[idx * 3 + 2]]
            if min(math.sqrt(sum((o[k] - c[k]) ** 2 for k in range(3))) for o in others) >= minsep:
                newp = push_out(c, mn, mx)
                h["pos_model"] = [round(float(t), 3) for t in newp]
                h["unit"] = to_unit(newp, mn, mx)
                moved = True
                break
        if not moved:
            crowded += 1

    frame = {"lat": axes[0], "up": axes[1], "len": axes[2],
             "nose_sign": int(nose), "shape_err": round(float(err), 3),
             "model_units_per_metre": round(float(scale), 4)}
    return hps, frame, crowded


